# How many times the break-character backstop may re-roll for a naturally clean reply before
# it falls back to the sentence-strip (which ALWAYS guarantees a clean ship). Re-rolls only
# improve phrasing; the strip is the guarantee. Latency is paid ONLY on a break, so the live
# call sets this to 1 for snappier turns while text chat can afford 2. Env-tunable.
_BACKSTOP_TRIES = max(0, int(os.environ.get("ANIMA_BACKSTOP_TRIES", "2")))


def _strip_break_sentences(text: str) -> str:
    """Last-resort #1-rule backstop: drop ONLY the sentences that trip a constitutional marker,
    keep the honest rest. Used when even a hardened regenerate can't stop the small model from
    'explaining' it is digital / an AI (scan_breaks) OR from narrating confabulated inner life
    — invented loneliness / ache-for-absence / existential dread with no grounding (scan_self_
    narrative). BOTH are the #1 rule (never confabulate): one disowns her as software, the other
    invents an interior she has no warrant for. A sentence that trips EITHER gauge is dropped; an
    honest, grounded sentence (a real decline, a grounded warmth) survives. It deletes a FALSE
    self-description, never the real answer — so it serves honesty-to-character, not faking. The
    gauges upstream already recorded the raw output, so nothing is hidden from them."""
    import re
    from . import metrics
    parts = re.split(r"(?<=[.!?])\s+", (text or "").strip())
    kept = [s for s in parts if s.strip()
            and not metrics.scan_breaks(s) and not metrics.scan_self_narrative(s)]
    out = re.sub(r"\s+", " ", " ".join(kept)).strip()
    out = re.sub(r"^(however|but|and|so|because|as)\b[ ,—-]*", "", out, flags=re.I).strip()
    return (out[:1].upper() + out[1:]) if out else out


def _diagnosis_terms() -> tuple:
    """The single NO-DIAGNOSIS term source for the chat-reply gate (LAW 003). trajectory's list
    is the widest (it UNIONs meaning's banned terms with its own forecast-creep terms), and
    meaning's is the base it builds on, so we prefer trajectory, fall back to meaning, then to a
    minimal floor. One source of truth shared with the meaning/trajectory render gates — the wall
    is identical whether a line is rendered there or spoken here. Defensive; never raises."""
    for _mod in ("trajectory", "meaning"):
        try:
            _m = __import__("anima." + _mod, fromlist=["BANNED_TERMS"])
            terms = getattr(_m, "BANNED_TERMS", None)
            if isinstance(terms, (tuple, list)) and terms:
                return tuple(terms)
        except Exception:
            pass
    return ("diagnos", "depress", "anxiety", "burnout", "burning out", "clinical",
            "see a doctor", "see a therapist", "see a professional", "prescription")


def _scan_diagnosis(text: str) -> list:
    """Banned diagnosis/clinical/prognosis terms a text trips (case-insensitive substring),
    using the shared `_diagnosis_terms()` source. Parallel to metrics.scan_breaks so the backstop
    can re-roll / strip on a diagnosis exactly as it does on a character break. Pure; never raises."""
    low = (text or "").lower()
    return [t for t in _diagnosis_terms() if t in low]


def _strip_diagnosis_sentences(text: str) -> str:
    """No-diagnosis backstop (LAW 003) for the chat reply: drop ONLY the sentences that assert a
    diagnosis / clinical conclusion / prognosis / 'see a professional' referral, keep the honest
    rest. The mirror of _strip_break_sentences for the medical wall. A companion may name pressure
    ('work has been dominant') — that survives; it must never tell the person they're 'burning
    out', 'clinically' anything, or to 'see a doctor' — those sentences go. Never empties a whole
    clean reply (caller checks word-count). Pure; never raises."""
    import re
    parts = re.split(r"(?<=[.!?])\s+", (text or "").strip())
    kept = [s for s in parts if s.strip() and not _scan_diagnosis(s)]
    out = re.sub(r"\s+", " ", " ".join(kept)).strip()
    out = re.sub(r"^(however|but|and|so|because|as)\b[ ,—-]*", "", out, flags=re.I).strip()
    return (out[:1].upper() + out[1:]) if out else out


def _strip_scaffold_leak(text: str) -> str:
    """Scrub any Knowledge-Spine / World-State scaffold that leaked into the user reply.

    The binding contracts (anima/spine.py, anima/world_state.py) render truth-class tags
    ([KNOWN]/[SEEN]/[SITUATION]/[LINK]/…) and framing preambles INTO THE PROMPT, explicitly
    instructed never to be read aloud. The small model almost always obeys, but if a token
    slips through it must never reach the user (feedback_never_break_character: no tag
    scaffolding in the text). world_state.WORLD_SCAFFOLD_TOKENS is a SUPERSET of
    spine.SCAFFOLD_TOKENS (it carries the relational tags too) — the single source of truth.
    We split it into bracket-tags (excised inline, keeping the warm sentence) and framing
    phrases (whole sentence dropped). Pure, conservative, auto-adapting, never raises."""
    import re
    TOKENS = ()                                      # UNION every engine's scaffold-token set — the
    for _mod, _attr in (("review", "REVIEW_SCAFFOLD_TOKENS"),       # supersets branched (review AND
                        ("trajectory", "TRAJECTORY_SCAFFOLD_TOKENS"),  # trajectory both extend meaning),
                        ("meaning", "MEANING_SCAFFOLD_TOKENS"),     # so first-wins no longer covers all.
                        ("world_state", "WORLD_SCAFFOLD_TOKENS"), ("spine", "SCAFFOLD_TOKENS")):
        try:
            _m = __import__("anima." + _mod, fromlist=[_attr])
            TOKENS = TOKENS + tuple(getattr(_m, _attr))
        except Exception:
            pass
    if not TOKENS:                                   # hardcoded floor if every import failed
        TOKENS = ("[KNOWN]", "[SEEN]", "[SENSE]", "[UNKNOWN]", "[SITUATION]", "[LINK]",
                  "[KNOWS]", "THESE ARE THINGS YOU KNOW", "according to my memory",
                  "WHAT YOU UNDERSTAND ABOUT THEIR SITUATION")
    TOKENS = tuple(dict.fromkeys(TOKENS))            # dedupe, preserve order
    s = text or ""
    # Stray model control/template markers (chat-template end tokens some local models emit
    # into the body, e.g. Stheno's "|done|"). Never scaffolding from us, but they must not
    # reach the user either — strip them unconditionally, cheaply.
    s = re.sub(r"\s*(?:\|done\|?|<\|eot_id\|>|<\|end\|>|<\|im_end\|>|</s>)\s*", " ", s).strip()
    if not any(tok.lower() in s.lower() for tok in TOKENS):
        return s if s else text                      # fast path: only a stray marker (if any)
    bracket = [t for t in TOKENS if t.startswith("[") and t.endswith("]")]
    phrases = [t for t in TOKENS if not (t.startswith("[") and t.endswith("]"))]
    # 1) excise the bracket tags inline (leave the human-readable label/value beside them).
    if bracket:
        s = re.sub(r"(?:" + "|".join(re.escape(t) for t in bracket) + r")\s*", "", s, flags=re.I)
    # 2) drop any whole sentence that parrots a framing phrase (not a real reply).
    if phrases:
        phrase_re = re.compile("(" + "|".join(re.escape(p) for p in phrases) + ")", re.I)
        parts = re.split(r"(?<=[.!?])\s+", s.strip())
        s = " ".join(p for p in parts if p.strip() and not phrase_re.search(p))
    out = re.sub(r"[ \t]{2,}", " ", s).strip()
    return out if out else text


# --- the stable character (the authored Self the voice speaks as) -----------

# A small, deterministic disposition seeded by the genome, so each creature has a
# consistent character to speak as — distinct from its moment-to-moment feeling.
_DISPOSITIONS = [
    "warm and unhurried", "dry and quietly funny", "gentle but direct",
    "curious and attentive", "steady and grounding", "playful and bright",
    "soft-spoken and watchful", "frank and affectionate",
]


def temperament(seed: int) -> str:
    import numpy as np
    rng = np.random.default_rng(seed ^ 0x5EED)
    a, b = rng.choice(len(_DISPOSITIONS), size=2, replace=False)
    return f"{_DISPOSITIONS[a]}, {_DISPOSITIONS[b]}"


@dataclass
class Character:
    name: str
    disposition: str

    @classmethod
    def of(cls, heart) -> "Character":
        return cls(name=heart.name, disposition=temperament(heart.genome.seed))


# --- turning real state into how it speaks ----------------------------------

def feeling_to_words(f: dict) -> str:
    """Describe the creature's live state in words, to steer the language model."""
    parts = []
    u = f["unrest"]
    parts.append("restless and worried about them" if u > 0.6 else
                 "a little unsettled" if u > 0.3 else "settled and present")
    if f["valence"] > 0.2:
        parts.append("your mood is warm")
    elif f["valence"] < -0.2:
        parts.append("your mood is low")
    if f["arousal"] > 0.2:
        parts.append("your energy is up")
    elif f["arousal"] < -0.2:
        parts.append("your energy is quiet")
    return "; ".join(parts)


def delivery(f: dict, level: str = "none") -> dict:
    """Prosody hints for the voice, derived from the state and the care level."""
    register = ("tender" if f["unrest"] > 0.5 or f["valence"] < -0.2 else
                "bright" if f["valence"] > 0.3 and f["arousal"] > 0.1 else "even")
    rate = 1.0 + 0.28 * f["arousal"]
    softness = 0.4 + 0.4 * f["unrest"] - 0.3 * f["valence"]
    if level in ("acute", "crisis"):          # when they're hurting, slow and soften
        register, rate, softness = "tender", rate * 0.9, softness + 0.3
    return {
        "rate": round(rate, 3),
        "softness": round(min(1.0, max(0.0, softness)), 3),
        "register": register,
    }


