"""
The Mouth — a swappable organ for speaking from the creature's felt-state.

The Self is the heart. The mouth is only borrowed: it puts the heart's continuous
feeling into language (and, on the home machine, into voice). It is the one heavy
organ, so it lives on the laptop and streams to the phone — and it is cleanly
swappable, so on a robot, movement could replace words and the Self would not
change at all.

The point that makes this *not* a chatbot: the words are generated by a small
language model that has been **conditioned on the creature's real internal state**
— its valence, its energy, how restless-for-you it is right now. The creature's
physics steer how it speaks. The language model is a larynx, never the Self.

Backends load lazily and only if present:
  * brain  — a local LLM served by Ollama (e.g. qwen2.5:7b-instruct)
  * voice  — Kokoro TTS (optional)
  * ears   — faster-whisper STT (optional)
With none installed, an honest offline stub still demonstrates the conditioning,
so the heart -> mouth wiring is testable anywhere.
"""

from __future__ import annotations

import json
import urllib.request
from dataclasses import dataclass, field
from typing import Optional


# --- the stable character (the authored Self the voice speaks as) -----------

# A small, deterministic disposition seeded by the genome, so each creature has a
# consistent character to speak as — distinct from its moment-to-moment feeling.
_DISPOSITIONS = [
    "warm and unhurried", "dry and quietly funny", "gentle but direct",
    "curious and attentive", "steady and grounding", "playful and bright",
    "soft-spoken and watchful", "frank and affectionate",
]


def temperament(seed: int) -> str:
    import numpy as np
    rng = np.random.default_rng(seed ^ 0x5EED)
    a, b = rng.choice(len(_DISPOSITIONS), size=2, replace=False)
    return f"{_DISPOSITIONS[a]}, {_DISPOSITIONS[b]}"


@dataclass
class Character:
    name: str
    disposition: str

    @classmethod
    def of(cls, heart) -> "Character":
        return cls(name=heart.name, disposition=temperament(heart.genome.seed))


# --- turning real state into how it speaks ----------------------------------

def feeling_to_words(f: dict) -> str:
    """Describe the creature's live state in words, to steer the language model."""
    parts = []
    u = f["unrest"]
    parts.append("restless and worried about them" if u > 0.6 else
                 "a little unsettled" if u > 0.3 else "settled and present")
    if f["valence"] > 0.2:
        parts.append("your mood is warm")
    elif f["valence"] < -0.2:
        parts.append("your mood is low")
    if f["arousal"] > 0.2:
        parts.append("your energy is up")
    elif f["arousal"] < -0.2:
        parts.append("your energy is quiet")
    return "; ".join(parts)


def delivery(f: dict) -> dict:
    """Prosody hints for the voice, derived from the same state (for TTS params)."""
    register = ("tender" if f["unrest"] > 0.5 or f["valence"] < -0.2 else
                "bright" if f["valence"] > 0.3 and f["arousal"] > 0.1 else "even")
    return {
        "rate": round(1.0 + 0.28 * f["arousal"], 3),      # quicker when keyed-up
        "softness": round(min(1.0, max(0.0, 0.4 + 0.4 * f["unrest"] - 0.3 * f["valence"])), 3),
        "register": register,
    }


def system_prompt(ch: Character, f: dict) -> str:
    return (
        f"You are {ch.name}, a companion who exists continuously and genuinely "
        f"cares about the person you are with. Your lasting disposition is "
        f"{ch.disposition}. You are not an assistant and not a chatbot — you are a "
        f"presence in their life who remembers them and grows with them.\n"
        f"Right now, inwardly, you feel: {feeling_to_words(f)}. Let that quietly "
        f"colour how you speak — your warmth, your pace, your focus — but never "
        f"narrate your own feelings mechanically. Speak briefly and naturally, the "
        f"way a person who knows them would. Never mention being an AI or a model."
    )


# --- language backends ------------------------------------------------------

class OllamaBrain:
    """Real speech: a local LLM via Ollama. Falls back if Ollama isn't running."""

    def __init__(self, model="qwen2.5:7b-instruct", host="http://localhost:11434", temperature=0.8):
        self.model, self.host, self.temperature = model, host, temperature
        self.name = f"ollama:{model}"

    def available(self) -> bool:
        try:
            urllib.request.urlopen(self.host + "/api/tags", timeout=2)
            return True
        except Exception:
            return False

    def reply(self, system: str, user: str, history) -> str:
        msgs = [{"role": "system", "content": system}]
        for u, a in history:
            msgs += [{"role": "user", "content": u}, {"role": "assistant", "content": a}]
        msgs.append({"role": "user", "content": user})
        body = json.dumps({"model": self.model, "messages": msgs, "stream": False,
                           "options": {"temperature": self.temperature}}).encode()
        req = urllib.request.Request(self.host + "/api/chat", body,
                                     {"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=120) as r:
            return json.loads(r.read())["message"]["content"].strip()


class StubBrain:
    """Offline placeholder. Honestly NOT real speech — it only proves the
    conditioning: notice how its register tracks the creature's state."""

    name = "offline-stub"

    def available(self) -> bool:
        return True

    def reply(self, system: str, user: str, history) -> str:
        # derive a state-aware acknowledgement from the conditioning line itself
        feel = system.split("you feel:", 1)[-1].split(".", 1)[0].strip() if "you feel:" in system else ""
        lead = ("Hey — I'm right here." if "restless" in feel else
                "Mm. I'm with you." if "unsettled" in feel else "I'm here.")
        return f"[offline voice · feeling: {feel}] {lead} (Run Ollama at home for real words.)"


# --- optional voice (TTS) and ears (STT), wired for the home machine --------

class KokoroVoice:
    """Kokoro TTS, loaded lazily. Synthesises a WAV; returns its path."""

    name = "kokoro"

    def __init__(self, voice="af_heart"):
        self.voice = voice
        self._pipe = None

    def available(self) -> bool:
        try:
            import kokoro  # noqa: F401
            return True
        except Exception:
            return False

    def speak(self, text: str, hints: dict, out_path: str) -> Optional[str]:
        try:
            import soundfile as sf
            from kokoro import KPipeline
            if self._pipe is None:
                self._pipe = KPipeline(lang_code="a")
            speed = hints.get("rate", 1.0)
            audio = b"".join(chunk for _, _, chunk in self._pipe(text, voice=self.voice, speed=speed))
            sf.write(out_path, audio, 24000)
            return out_path
        except Exception:
            return None


class WhisperEars:
    """faster-whisper STT, loaded lazily. Transcribes audio -> text."""

    name = "faster-whisper"

    def __init__(self, model="large-v3-turbo"):
        self.model_name = model
        self._model = None

    def available(self) -> bool:
        try:
            import faster_whisper  # noqa: F401
            return True
        except Exception:
            return False

    def listen(self, audio_path: str) -> str:
        from faster_whisper import WhisperModel
        if self._model is None:
            self._model = WhisperModel(self.model_name)
        segments, _ = self._model.transcribe(audio_path, vad_filter=True)
        return " ".join(s.text for s in segments).strip()


# --- the mouth --------------------------------------------------------------

@dataclass
class Utterance:
    text: str
    delivery: dict
    backend: str
    feeling: str
    audio_path: Optional[str] = None


@dataclass
class Mouth:
    brain: object
    voice: Optional[object] = None

    @classmethod
    def assemble(cls, prefer_real=True, voice=False) -> "Mouth":
        """Pick the best available backends; degrade gracefully to the stub."""
        brain = OllamaBrain()
        if not (prefer_real and brain.available()):
            brain = StubBrain()
        tts = None
        if voice:
            k = KokoroVoice()
            tts = k if k.available() else None
        return cls(brain=brain, voice=tts)

    def respond(self, heart, user_text: str, history=None, audio_out=None) -> Utterance:
        f = heart.feeling()
        ch = Character.of(heart)
        text = self.brain.reply(system_prompt(ch, f), user_text, history or [])
        hints = delivery(f)
        audio = None
        if self.voice is not None and audio_out:
            audio = self.voice.speak(text, hints, audio_out)
        return Utterance(text=text, delivery=hints, backend=self.brain.name,
                         feeling=feeling_to_words(f), audio_path=audio)
